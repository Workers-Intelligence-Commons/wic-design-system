// Writes src/marks.generated.ts from the monogram files in the tokens package, so the Mark component
// draws exactly what the logo files hold. Each file's groups are filled with the light ink and red
// of tokens.json; the component swaps those fills for the theme variables.
const tokensDir = new URL("../../tokens/", import.meta.url).pathname;
const out = new URL("../src/marks.generated.ts", import.meta.url).pathname;

const tokens: { color: { tokens: { name: string; value: { light: string } }[] } } = await Bun.file(`${tokensDir}tokens.json`).json();
const light = (name: string) => tokens.color.tokens.find((t) => t.name === name)!.value.light;
const inkFill = light("ink");
const redFill = light("red");

type Shape = { type: "polygon"; points: string } | { type: "path"; d: string; fillRule?: "evenodd" };

function attr(tag: string, name: string): string | undefined {
  return tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
}

function shapes(group: string): Shape[] {
  return [...group.matchAll(/<(polygon|path)\b[^>]*\/>/g)].map(([tag, type]) => {
    if (type === "polygon") return { type, points: attr(tag, "points")! };
    const fillRule = attr(tag, "fill-rule");
    return fillRule === "evenodd" ? { type: "path", d: attr(tag, "d")!, fillRule } : { type: "path", d: attr(tag, "d")! };
  });
}

async function mark(name: string) {
  const svg = await Bun.file(`${tokensDir}logos/${name}-mark.svg`).text();
  const root = svg.match(/<svg\b[^>]*>/)![0];
  const groups = new Map([...svg.matchAll(/<g fill="([^"]+)">(.*?)<\/g>/g)].map(([, fill, body]) => [fill.toLowerCase(), body]));
  const ink = groups.get(inkFill.toLowerCase());
  const red = groups.get(redFill.toLowerCase());
  if (ink === undefined || red === undefined || groups.size !== 2) throw new Error(`${name}-mark.svg must hold one ${inkFill} group and one ${redFill} group`);
  return { viewBox: attr(root, "viewBox")!, width: Number(attr(root, "width")), height: Number(attr(root, "height")), ink: shapes(ink), red: shapes(red) };
}

const marks = { wpt: await mark("wpt"), wic: await mark("wic"), hub: await mark("hub") };
await Bun.write(
  out,
  `// Generated by scripts/marks.ts from packages/tokens/logos. Do not edit.\n` +
    `// The drawings are the WPT and WIC monograms: not licensed, all rights reserved (see NOTICE).\n` +
    `export const MARKS = ${JSON.stringify(marks, null, 2)} as const;\n`,
);
